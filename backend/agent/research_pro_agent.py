# backend/agent/research_pro_agent.py — Deep Research Agent
# Multi-source search + page extraction + cited synthesis, saved as Markdown.
from __future__ import annotations

import re
import time
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List

import requests
from bs4 import BeautifulSoup

import config
from backend.study.citation_gen import citations
from .advanced_common import (
    ask,
    clean_text,
    extract_after,
    fail,
    ok,
    slugify,
    truncate,
    write_json,
)

HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) Atlas/7.0 Research",
    "Accept-Language": "en-US,en;q=0.8,bn;q=0.6",
}
DDG_URL = "https://html.duckduckgo.com/html/?q={query}"
WIKI_URL = "https://en.wikipedia.org/w/api.php"


class ResearchProAgent:
    name = "Deep Research Agent"

    def get_capabilities(self) -> List[str]:
        return ["deep_research", "research_report", "cite_sources", "source_cross_check"]

    def handle(self, intent: str, entities: Dict[str, Any]) -> Dict[str, Any]:
        entities = entities or {}
        command = str(entities.get("_command", ""))
        intent_lower = str(intent or "").lower()

        try:
            if "citation" in intent_lower or "cite" in intent_lower:
                return self.make_citation(entities)
            topic = str(
                entities.get("topic")
                or entities.get("query")
                or extract_after(command, ["deep research", "research report", "গভীর গবেষণা", "research on", "research about", "গবেষণা"])
                or ""
            ).strip()
            if not topic:
                return fail("research_pro", "কোন topic নিয়ে research করব? যেমন: “deep research on AI in healthcare”।")
            return self.deep_research(
                topic,
                max_sources=int(entities.get("max_sources") or 4),
                language=str(entities.get("language") or "auto"),
            )
        except Exception as exc:
            return fail("research_pro", f"Research Agent error: {exc}")

    # ---------------- actions ----------------
    def deep_research(self, topic: str, max_sources: int = 4, language: str = "auto") -> Dict[str, Any]:
        started = time.time()
        max_sources = max(1, min(max_sources, 6))
        sources = self._search(topic, max_sources)
        if not sources:
            fallback = ask(
                f"Write a careful research briefing on: {topic}. Include key facts, open questions, and clearly mark uncertain claims.",
                system_prompt="You are a research analyst. Never invent citations. Reply in the user's language.",
            )
            return fail(
                "research_pro",
                "Live source search পাওয়া যায়নি; AI-only briefing তৈরি হয়েছে (citation ছাড়া)।",
                topic=topic,
                briefing=truncate(fallback, 5000) if fallback else "",
                sources=[],
            )

        for source in sources:
            if source.get("url"):
                source["text"] = self._fetch_text(source["url"])

        context_blocks = []
        for index, source in enumerate(sources, 1):
            context_blocks.append(
                f"[{index}] {source.get('title') or 'Untitled'}\nURL: {source.get('url')}\n"
                f"Snippet: {source.get('snippet') or ''}\nExcerpt: {truncate(source.get('text') or '', 2500)}"
            )

        report = ask(
            "Write a structured research briefing using ONLY the sources below.\n"
            f"Topic: {topic}\n\n" + "\n\n".join(context_blocks) + "\n\n"
            "Format: Executive summary, Key findings (with [n] citations), Conflicting views, "
            "Practical implications, Limitations, Sources. Reply in the user's language.",
            system_prompt="You are a rigorous research analyst. Cite source numbers exactly as provided. Do not invent facts.",
        )

        source_list = [
            {"index": i, "title": s.get("title") or "", "url": s.get("url") or "", "snippet": s.get("snippet") or ""}
            for i, s in enumerate(sources, 1)
        ]
        if not report:
            report = self._extractive_report(topic, sources)

        folder = config.DATA_DIR / "research"
        folder.mkdir(parents=True, exist_ok=True)
        path = folder / f"{slugify(topic)}-{datetime.now().strftime('%Y%m%d-%H%M%S')}.md"
        lines = [
            f"# Research: {topic}",
            "",
            f"_Generated by Atlas Deep Research on {datetime.now().strftime('%Y-%m-%d %H:%M')}_",
            "",
            report.strip(),
            "",
            "## Sources",
            "",
        ]
        for source in source_list:
            lines.append(f"{source['index']}. [{source['title']}]({source['url']})")
        path.write_text("\n".join(lines), encoding="utf-8")

        return ok(
            "research_pro",
            f"🔎 Research complete — {len(sources)} source(s).",
            topic=topic,
            report=truncate(report, 8000),
            sources=source_list,
            report_path=str(path),
            duration_ms=int((time.time() - started) * 1000),
        )

    def make_citation(self, entities: Dict[str, Any]) -> Dict[str, Any]:
        fields = {
            "authors": entities.get("authors") or entities.get("author") or "",
            "title": entities.get("title") or entities.get("topic") or "",
            "year": entities.get("year") or "",
            "publisher": entities.get("publisher") or "",
            "journal": entities.get("journal") or "",
            "url": entities.get("url") or "",
            "volume": entities.get("volume") or "",
            "pages": entities.get("pages") or "",
            "accessed": entities.get("accessed") or datetime.now().strftime("%Y-%m-%d"),
        }
        if not fields["title"] and not fields["url"]:
            return fail("research_pro", "Citation-এর জন্য title/url দিন।")
        style = str(entities.get("style") or "apa").lower()
        try:
            result = citations.format(fields, style=style)
            return ok("research_pro", result["citation"], **result)
        except Exception as exc:
            return fail("research_pro", f"Citation error: {exc}")

    # ---------------- search / fetch ----------------
    def _search(self, topic: str, limit: int) -> List[Dict[str, str]]:
        results: List[Dict[str, str]] = []
        try:
            response = requests.get(DDG_URL.format(query=requests.utils.quote(topic)), headers=HEADERS, timeout=10)
            if response.status_code == 200:
                soup = BeautifulSoup(response.text, "html.parser")
                for item in soup.select(".result"):
                    link = item.select_one(".result__a")
                    snippet = item.select_one(".result__snippet")
                    if not link or not link.get("href"):
                        continue
                    url = link.get("href", "")
                    if "duckduckgo.com/l/?uddg=" in url:
                        from urllib.parse import parse_qs, urlparse
                        query = parse_qs(urlparse(url).query)
                        url = (query.get("uddg") or [url])[0]
                    results.append({
                        "title": clean_text(link.get_text(" ")),
                        "url": url,
                        "snippet": clean_text(snippet.get_text(" ")) if snippet else "",
                    })
                    if len(results) >= limit:
                        break
        except Exception:
            pass

        if len(results) < limit:
            results.extend(self._wiki_search(topic, limit - len(results)))
        return results[:limit]

    def _wiki_search(self, topic: str, limit: int) -> List[Dict[str, str]]:
        try:
            response = requests.get(
                WIKI_URL,
                params={
                    "action": "query", "list": "search", "srsearch": topic,
                    "format": "json", "srlimit": max(1, min(limit, 5)),
                },
                headers=HEADERS,
                timeout=10,
            )
            data = response.json()
            out = []
            for item in (data.get("query", {}).get("search") or [])[:limit]:
                title = item.get("title", "")
                out.append({
                    "title": title,
                    "url": "https://en.wikipedia.org/wiki/" + title.replace(" ", "_"),
                    "snippet": clean_text(re.sub(r"<[^>]+>", " ", item.get("snippet", ""))),
                })
            return out
        except Exception:
            return []

    def _fetch_text(self, url: str) -> str:
        try:
            response = requests.get(url, headers=HEADERS, timeout=10, allow_redirects=True)
            if response.status_code != 200 or "text/html" not in response.headers.get("Content-Type", ""):
                return ""
            soup = BeautifulSoup(response.content[:1_500_000], "html.parser")
            for tag in soup(["script", "style", "nav", "footer", "header", "aside", "form"]):
                tag.decompose()
            text = " ".join(soup.get_text(" ").split())
            return truncate(text, 6000)
        except Exception:
            return ""

    @staticmethod
    def _extractive_report(topic: str, sources: List[Dict[str, str]]) -> str:
        lines = [f"# {topic}", "", "## Source snippets", ""]
        for index, source in enumerate(sources, 1):
            lines.append(f"[{index}] **{source.get('title') or 'Untitled'}** — {source.get('snippet') or ''}")
            if source.get("text"):
                lines.append(f"> {truncate(source['text'], 700)}")
            lines.append("")
        lines.append("_AI synthesis unavailable; showing extracted source material._")
        return "\n".join(lines)

    def test(self) -> Dict[str, Any]:
        try:
            requests.get("https://html.duckduckgo.com/", headers=HEADERS, timeout=5)
            network = True
        except Exception:
            network = False
        return {
            "success": True,
            "agent": "research_pro",
            "network": network,
            "message": "Deep Research ready (DuckDuckGo + Wikipedia fallback).",
        }


research_pro_agent = ResearchProAgent()
